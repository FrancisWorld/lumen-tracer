// Generates the procedural assets that ship with the example scenes:
//   textures/mosaic.png   hand-glazed tile mosaic
//   models/knot.obj       (2,3) torus knot with normals and uv
//   models/rock.obj       displaced icosphere
// The output is fully deterministic, so the committed files can be re-created
// byte for byte:  lumen-assets assets
#include <array>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <map>
#include <string>
#include <vector>

#include "lumen/math.hpp"
#include "lumen/png.hpp"
#include "lumen/rng.hpp"

using namespace lumen;

namespace {

void write_mosaic(const std::filesystem::path& path) {
    constexpr std::uint32_t kSize = 256;
    constexpr std::uint32_t kTile = 32;
    constexpr std::uint32_t kGrout = 2;
    static constexpr std::array<std::array<float, 3>, 5> palette = {{{0.78F, 0.32F, 0.20F},
                                                                      {0.92F, 0.72F, 0.30F},
                                                                      {0.18F, 0.45F, 0.52F},
                                                                      {0.88F, 0.84F, 0.76F},
                                                                      {0.30F, 0.22F, 0.40F}}};
    Image8 img{kSize, kSize, 3, Bytes(static_cast<std::size_t>(kSize) * kSize * 3)};
    for (std::uint32_t y = 0; y < kSize; ++y) {
        for (std::uint32_t x = 0; x < kSize; ++x) {
            const std::uint32_t tx = x / kTile;
            const std::uint32_t ty = y / kTile;
            Pcg32 tile_rng(hash_combine(tx, ty));
            const auto& base = palette[tile_rng.next_u32() % palette.size()];
            const float tint = 0.85F + 0.3F * tile_rng.next_real();
            const std::uint32_t lx = x % kTile;
            const std::uint32_t ly = y % kTile;
            const bool grout = lx < kGrout || ly < kGrout;
            // Glaze: soft bevel towards the tile edge plus fine per-pixel grain.
            const float edge = static_cast<float>(std::min({lx, ly, kTile - 1 - lx, kTile - 1 - ly}));
            const float bevel = 0.75F + 0.25F * std::min(edge / 6.0F, 1.0F);
            Pcg32 grain(hash_combine(x, y + 1000003ULL));
            const float noise = 0.96F + 0.08F * grain.next_real();
            for (std::uint32_t c = 0; c < 3; ++c) {
                const float v = grout ? 0.55F * noise : std::min(1.0F, base[c] * tint * bevel * noise);
                img.pixels[(static_cast<std::size_t>(y) * kSize + x) * 3 + c] = static_cast<std::uint8_t>(v * 255.0F + 0.5F);
            }
        }
    }
    write_png_file(path.string(), img);
}

void write_vertex(std::ofstream& out, const char* tag, double a, double b, double c = 0, bool three = true) {
    char buf[96];
    if (three) {
        std::snprintf(buf, sizeof buf, "%s %.5g %.5g %.5g\n", tag, a, b, c);
    } else {
        std::snprintf(buf, sizeof buf, "%s %.5g %.5g\n", tag, a, b);
    }
    out << buf;
}

void write_knot(const std::filesystem::path& path) {
    constexpr int kSegments = 160;
    constexpr int kSides = 20;
    constexpr double kP = 2;
    constexpr double kQ = 3;
    constexpr double kTube = 0.28;
    auto curve = [&](double t) {
        const double r = std::cos(kQ * t) + 2.0;
        return Vec3(static_cast<Real>(r * std::cos(kP * t)), static_cast<Real>(r * std::sin(kP * t)),
                    static_cast<Real>(-std::sin(kQ * t)));
    };
    std::ofstream out(path);
    out << "# (2,3) torus knot generated by lumen-assets\n";
    const double two_pi = 2.0 * std::numbers::pi;
    for (int i = 0; i <= kSegments; ++i) {
        const double t = two_pi * i / kSegments;
        const double h = 1e-3;
        const Vec3 c = curve(t);
        const Vec3 tangent = normalize(curve(t + h) - curve(t - h));
        const Vec3 accel = curve(t + h) + curve(t - h) - c * 2.0F;
        const Vec3 n = normalize(accel - tangent * dot(accel, tangent));  // Frenet normal: knot curvature never vanishes
        const Vec3 b = cross(tangent, n);
        for (int j = 0; j <= kSides; ++j) {
            const double a = two_pi * j / kSides;
            const Vec3 radial = n * static_cast<Real>(std::cos(a)) + b * static_cast<Real>(std::sin(a));
            const Vec3 p = c + radial * static_cast<Real>(kTube);
            write_vertex(out, "v", p.x, p.y, p.z);
        }
    }
    for (int i = 0; i <= kSegments; ++i) {
        for (int j = 0; j <= kSides; ++j) {
            write_vertex(out, "vt", static_cast<double>(i) / kSegments * 6.0, static_cast<double>(j) / kSides, 0, false);
        }
    }
    // Normals: derived from the grid so the surface shades smoothly.
    std::vector<Vec3> positions;
    {
        std::ifstream in(path);
        std::string line;
        while (std::getline(in, line)) {
            float x = 0;
            float y = 0;
            float z = 0;
            if (std::sscanf(line.c_str(), "v %f %f %f", &x, &y, &z) == 3) {
                positions.emplace_back(x, y, z);
            }
        }
    }
    auto at = [&](int i, int j) {
        const int ii = ((i % kSegments) + kSegments) % kSegments;
        const int jj = ((j % kSides) + kSides) % kSides;
        return positions[static_cast<std::size_t>(ii * (kSides + 1) + jj)];
    };
    for (int i = 0; i <= kSegments; ++i) {
        for (int j = 0; j <= kSides; ++j) {
            const Vec3 n = normalize(cross(at(i + 1, j) - at(i - 1, j), at(i, j + 1) - at(i, j - 1)));
            write_vertex(out, "vn", n.x, n.y, n.z);
        }
    }
    auto idx = [&](int i, int j) { return i * (kSides + 1) + j + 1; };
    for (int i = 0; i < kSegments; ++i) {
        for (int j = 0; j < kSides; ++j) {
            const int a = idx(i, j);
            const int b = idx(i + 1, j);
            const int c = idx(i + 1, j + 1);
            const int d = idx(i, j + 1);
            char buf[160];
            std::snprintf(buf, sizeof buf, "f %d/%d/%d %d/%d/%d %d/%d/%d\nf %d/%d/%d %d/%d/%d %d/%d/%d\n", a, a, a, b,
                          b, b, c, c, c, a, a, a, c, c, c, d, d, d);
            out << buf;
        }
    }
}

void write_rock(const std::filesystem::path& path) {
    // Icosahedron subdivided three times, vertices pushed along their normal by layered sines.
    const double t = (1.0 + std::sqrt(5.0)) / 2.0;
    std::vector<Vec3> v;
    for (const auto& p : std::vector<std::array<double, 3>>{{-1, t, 0}, {1, t, 0}, {-1, -t, 0}, {1, -t, 0}, {0, -1, t}, {0, 1, t},
                                                           {0, -1, -t}, {0, 1, -t}, {t, 0, -1}, {t, 0, 1}, {-t, 0, -1}, {-t, 0, 1}}) {
        v.push_back(normalize(Vec3(static_cast<Real>(p[0]), static_cast<Real>(p[1]), static_cast<Real>(p[2]))));
    }
    std::vector<std::array<int, 3>> faces = {{0, 11, 5}, {0, 5, 1},  {0, 1, 7},  {0, 7, 10}, {0, 10, 11}, {1, 5, 9},  {5, 11, 4},
                                             {11, 10, 2}, {10, 7, 6}, {7, 1, 8},  {3, 9, 4},  {3, 4, 2},   {3, 2, 6},  {3, 6, 8},
                                             {3, 8, 9},  {4, 9, 5},  {2, 4, 11}, {6, 2, 10}, {8, 6, 7},   {9, 8, 1}};
    for (int level = 0; level < 3; ++level) {
        std::map<std::pair<int, int>, int> midpoints;
        auto mid = [&](int a, int b) {
            const auto key = std::minmax(a, b);
            const auto it = midpoints.find(key);
            if (it != midpoints.end()) {
                return it->second;
            }
            v.push_back(normalize(v[static_cast<std::size_t>(a)] + v[static_cast<std::size_t>(b)]));
            return midpoints[key] = static_cast<int>(v.size() - 1);
        };
        std::vector<std::array<int, 3>> next;
        for (const auto& f : faces) {
            const int ab = mid(f[0], f[1]);
            const int bc = mid(f[1], f[2]);
            const int ca = mid(f[2], f[0]);
            next.push_back({f[0], ab, ca});
            next.push_back({f[1], bc, ab});
            next.push_back({f[2], ca, bc});
            next.push_back({ab, bc, ca});
        }
        faces = std::move(next);
    }
    std::vector<Vec3> p(v.size());
    for (std::size_t i = 0; i < v.size(); ++i) {
        const Vec3 d = v[i];
        double bump = 0.12 * std::sin(3.1 * d.x + 1.3) * std::sin(2.7 * d.y + 0.4) + 0.07 * std::sin(6.3 * d.z + 2.0 * d.x) +
                      0.035 * std::sin(11.0 * d.x + 9.0 * d.y + 5.0 * d.z);
        p[i] = d * static_cast<Real>(1.0 + bump) * Vec3(1.15F, 0.85F, 1.0F);
    }
    std::vector<Vec3> n(v.size());
    for (const auto& f : faces) {
        const auto a = static_cast<std::size_t>(f[0]);
        const auto b = static_cast<std::size_t>(f[1]);
        const auto c = static_cast<std::size_t>(f[2]);
        const Vec3 fn = cross(p[b] - p[a], p[c] - p[a]);  // area weighted
        n[a] += fn;
        n[b] += fn;
        n[c] += fn;
    }
    std::ofstream out(path);
    out << "# displaced icosphere generated by lumen-assets\n";
    for (const Vec3& q : p) {
        write_vertex(out, "v", q.x, q.y, q.z);
    }
    for (const Vec3& q : n) {
        const Vec3 u = normalize(q);
        write_vertex(out, "vn", u.x, u.y, u.z);
    }
    for (const auto& f : faces) {
        char buf[96];
        std::snprintf(buf, sizeof buf, "f %d//%d %d//%d %d//%d\n", f[0] + 1, f[0] + 1, f[1] + 1, f[1] + 1, f[2] + 1, f[2] + 1);
        out << buf;
    }
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 2) {
        std::fputs("usage: lumen-assets <output-directory>\n", stderr);
        return 2;
    }
    try {
        const std::filesystem::path root(argv[1]);
        std::filesystem::create_directories(root / "textures");
        std::filesystem::create_directories(root / "models");
        write_mosaic(root / "textures" / "mosaic.png");
        write_knot(root / "models" / "knot.obj");
        write_rock(root / "models" / "rock.obj");
        std::puts("assets written");
        return 0;
    } catch (const std::exception& e) {
        std::fprintf(stderr, "lumen-assets: %s\n", e.what());
        return 1;
    }
}
